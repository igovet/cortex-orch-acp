"""Deterministic, offline Workspace schema generation (check or write)."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = "src/cortex_runtime/workspace_contract/schema.json"
LOCK_PATH = "src/cortex_runtime/workspace_contract/schema-lock.json"
FINGERPRINT_PATH = "src/cortex_runtime/workspace_contract/schema.sha256"


def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False,
                      separators=(",", ":"), allow_nan=False)


def pretty(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def ts_type(spec):
    if "$ref" in spec:
        return spec["$ref"].rsplit("/", 1)[1]
    if "const" in spec:
        return canonical(spec["const"])
    if "enum" in spec:
        return " | ".join(canonical(item) for item in spec["enum"])
    for union in ("oneOf", "anyOf"):
        if union in spec:
            return " | ".join(ts_type(item) for item in spec[union])
    kind = spec.get("type")
    if kind == "object":
        fields = [canonical(key) + ("" if key in spec.get("required", []) else "?")
                  + ": " + ts_type(value) for key, value in spec.get("properties", {}).items()]
        if spec.get("additionalProperties", True):
            fields.append("[key: string]: unknown")
        return "{ " + "; ".join(fields) + " }"
    if kind == "array":
        return "(" + ts_type(spec["items"]) + ")[]"
    return {"string": "string", "integer": "number", "null": "null", "boolean": "boolean"}[kind]


def check_subset(schema):
    allowed = {"$schema", "$id", "title", "$defs", "$ref", "type", "properties",
               "required", "additionalProperties", "items", "maxItems", "minItems",
               "uniqueItems", "maxLength", "minLength", "pattern", "minimum",
               "maximum", "const", "enum", "oneOf", "anyOf"}
    patterns = {"^(0|[1-9][0-9]*)$", "^[1-9][0-9]*$", "^[0-9a-f]{64}$"}
    def visit(spec):
        if any(key not in allowed and not key.startswith("x-") for key in spec):
            raise ValueError("unsupported schema keyword")
        if spec.get("type") not in {None, "object", "array", "string", "integer", "null", "boolean"}:
            raise ValueError("unsupported schema type")
        if "pattern" in spec and spec["pattern"] not in patterns:
            raise ValueError("unsupported schema pattern")
        if "$ref" in spec and spec["$ref"] not in {"#/$defs/" + name for name in schema["$defs"]}:
            raise ValueError("unsupported schema reference")
        for child in spec.get("properties", {}).values():
            visit(child)
        if "items" in spec:
            visit(spec["items"])
        for union in ("oneOf", "anyOf"):
            for child in spec.get(union, []):
                visit(child)
    for definition in schema["$defs"].values():
        visit(definition)


def render(schema, lock):
    check_subset(schema)
    limits, definitions = schema["x-limits"], schema["$defs"]
    if (definitions["Attachments"]["maxItems"] != limits["attachmentFiles"]
            or definitions["Attachment"]["properties"]["data"]["maxLength"] != (limits["attachmentBytes"] + 2) // 3 * 4):
        raise ValueError("attachment schema bounds must derive from x-limits")
    version = schema["x-wire-version"]
    version_key = str(version["major"]) + "." + str(version["minor"])
    digest = hashlib.sha256(canonical(schema).encode("utf-8")).hexdigest()
    if version_key in lock and lock[version_key] != digest:
        raise ValueError("schema changed: bump wire version; existing version fingerprints are immutable")
    updated_lock = dict(lock, **{version_key: digest})
    definitions = schema["$defs"]
    types = "// Generated by scripts/generate_workspace_contract.py; do not edit.\n"
    for name, spec in definitions.items():
        types += "export type " + name + " = " + ts_type(spec) + ";\n"
    types += "export interface WireTypes { " + "; ".join(name + ": " + name for name in definitions) + " }\n"
    constants = {"PROTOCOL": version, "SCHEMA_FINGERPRINT": digest,
                 "MAPPING_VERSION": schema["x-mapping-version"],
                 "LIMITS": schema["x-limits"], "OPERATIONS": schema["x-operations"]}
    for key, value in constants.items():
        types += "export const " + key + " = " + canonical(value) + " as const;\n"
    types += "export { validate, decodeResponse, capabilities, negotiate, encodeFrame, decodeFrame } from './runtime.js';\n"
    js = "// Generated by scripts/generate_workspace_contract.py; do not edit.\n"
    for key, value in constants.items():
        js += "export const " + key + " = " + canonical(value) + ";\n"
    js += "export { validate, decodeResponse, capabilities, negotiate, encodeFrame, decodeFrame } from './runtime.js';\n"
    fixtures = json.loads(json.dumps(schema["x-fixtures"]).replace("$fingerprint", digest))
    rust = "// Generated by scripts/generate_workspace_contract.py; do not edit.\n"
    rust += "pub const SCHEMA_FINGERPRINT: &str =\n    " + canonical(digest) + ";\n"
    rust += "pub const WIRE_MAJOR: u64 = " + str(version["major"]) + ";\n"
    rust += "pub const WIRE_MINOR: u64 = " + str(version["minor"]) + ";\n"
    for key, value in schema["x-limits"].items():
        constant = "".join("_" + char if char.isupper() else char for char in key).upper()
        rust += "pub const " + constant + ": usize = " + str(value) + ";\n"
    for name in definitions:
        rust_name = {"Result": "WorkspaceResult", "Option": "DecisionOption"}.get(name, name)
        rust += '''
#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
#[serde(try_from = "serde_json::Value", into = "serde_json::Value")]
pub struct NAME {
    value: serde_json::Value,
    warnings: Vec<String>,
}
impl TryFrom<serde_json::Value> for NAME {
    type Error = String;
    fn try_from(value: serde_json::Value) -> Result<Self, Self::Error> {
        let (value, warnings) = crate::decode_response("NAME", &value)?;
        Ok(Self { value, warnings })
    }
}
impl From<NAME> for serde_json::Value {
    fn from(value: NAME) -> Self {
        value.value
    }
}
impl NAME {
    pub fn as_value(&self) -> &serde_json::Value {
        &self.value
    }
    pub fn warnings(&self) -> &[String] {
        &self.warnings
    }
}
'''.replace('"NAME"', canonical(name)).replace("NAME", rust_name)
    ts_fixtures = "// Generated valid compile-time vectors; JSON validation is separate.\n"
    ts_fixtures += "import type { " + ", ".join(definitions) + " } from './index.js';\n"
    for index, fixture in enumerate(fixtures):
        if fixture["valid"]:
            ts_fixtures += "export const vector" + str(index) + " = " + canonical(fixture["value"]) + " satisfies " + fixture["type"] + ";\n"
    rust += "\npub fn decode_typed(\n    name: &str,\n    value: serde_json::Value,\n) -> std::result::Result<(serde_json::Value, Vec<String>), String> {\n    match name {\n"
    for name in definitions:
        rust_name = {"Result": "WorkspaceResult", "Option": "DecisionOption"}.get(name, name)
        rust += ('        "' + name + '" => serde_json::from_value::<' + rust_name + '>(value)\n'
                 '            .map(|decoded| (decoded.as_value().clone(), decoded.warnings().to_vec()))\n'
                 '            .map_err(|_| "invalid_wire_value".into()),\n')
    rust += '        _ => Err("unknown_type".into()),\n    }\n}\n'
    return {FINGERPRINT_PATH: digest + "\n", LOCK_PATH: pretty(updated_lock),
            "packages/workspace-contract/fixtures.ts": ts_fixtures,
            "packages/workspace-contract/schema.json": pretty(schema),
            "packages/workspace-contract/fixtures.json": pretty(fixtures),
            "packages/workspace-contract/index.ts": types,
            "packages/workspace-contract/index.js": js,
            "crates/workspace-protocol/src/generated.rs": rust}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("check", "write"))
    args = parser.parse_args()
    try:
        schema = json.loads((ROOT / SCHEMA_PATH).read_text(encoding="utf-8"))
        lock_path = ROOT / LOCK_PATH
        if args.action == "check" and not lock_path.exists():
            raise ValueError("missing schema version lock")
        lock = json.loads(lock_path.read_text()) if lock_path.exists() else {}
        outputs = render(schema, lock)
        drift = []
        for path, content in outputs.items():
            target = ROOT / path
            if args.action == "write":
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")
            elif not target.exists() or target.read_text(encoding="utf-8") != content:
                drift.append(path)
        if drift:
            print("Workspace contract drift: " + ", ".join(drift), file=sys.stderr)
            return 1
    except (ValueError, KeyError) as error:
        print(str(error), file=sys.stderr)
        return 1
    print("Workspace contract " + args.action + ": OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
